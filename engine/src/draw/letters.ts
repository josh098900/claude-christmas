export interface HandStyle {
  seed?: number;
  color?: string;
  weight?: number;   // stroke width as fraction of size*0.1
  slant?: number;    // italic shear
  wobble?: number;   // jitter amount
  tracking?: number; // extra letter spacing
  boil?: number;     // boil index (0 = static)
  baseline?: number; // baseline wander amount
  passes?: number;   // 1 = marker, 2+ = pencil
  alpha?: number;
  progress?: number; // 0..1 how much of the text is written (animate writing)
  align?: 'left' | 'center' | 'right';
}

export function measure(text: string, size: number, st: HandStyle = {}): number {
  let w = 0;
  for (const ch of text) {
    if (ch === ' ') { w += size * 0.45; continue; }
    const g = G[ch] || G[ch.toUpperCase()];
    w += ((g ? g.w : 0.5) + 0.26 + (st.tracking || 0)) * size;
  }
  return w - 0.26 * size;
}

/** Draws hand-lettered text. (x,y) = left (or aligned) baseline-top: y is the top of capitals. Returns width. */
export function handText(ctx: C2D, text: string, x: number, y: number, size: number, st: HandStyle = {}): number {
  const seed = st.seed ?? 1, boil = st.boil ?? 0;
  const wob = (st.wobble ?? 1) * 0.022;
  const slant = st.slant ?? 0.06;
  const lw = Math.max(0.6, size * 0.1 * (st.weight ?? 1));
  const total = measure(text, size, st);
  if (st.align === 'center') x -= total / 2; else if (st.align === 'right') x -= total;
  const nChars = [...text].length;
  const prog = st.progress ?? 1;
  ctx.save();
  ctx.lineCap = 'round'; ctx.lineJoin = 'round';
  ctx.strokeStyle = st.color || '#2b2b33';
  let cx = x, ci = 0;
  for (const ch of text) {
    if (ci / nChars >= prog) break;
    ci++;
    if (ch === ' ') { cx += size * 0.45; continue; }
    const g = G[ch] || G[ch.toUpperCase()];
    if (!g) { cx += size * 0.5; continue; }
    const by = y + noise1(ci * 0.6, seed) * size * 0.05 * (st.baseline ?? 1);
    const rot = noise1(ci * 0.9 + 7, seed) * 0.05;
    const sc = 1 + noise1(ci * 1.3 + 3, seed) * 0.05;
    for (let si = 0; si < g.s.length; si++) {
      const pts: V2[] = g.s[si].map(([px, py], k) => {
        let gx = px * sc, gy = py * sc;
        gx += (1 - gy) * slant;
        const rx = gx * Math.cos(rot) - (gy - 0.5) * Math.sin(rot);
        const ry = gx * Math.sin(rot) + (gy - 0.5) * Math.cos(rot) + 0.5;
        return v2(cx + rx * size + jit(seed + ci * 13 + si, k * 2, boil) * size * wob,
                  by + ry * size + jit(seed + ci * 13 + si, k * 2 + 1, boil) * size * wob);
      });
      const passes = st.passes ?? 1;
      for (let p = 0; p < passes; p++) {
        ctx.globalAlpha = (st.alpha ?? 1) * (p === 0 ? 1 : 0.45);
        ctx.lineWidth = lw * (p === 0 ? 1 : 0.6);
        ctx.beginPath();
        if (pts.length === 2 && Math.hypot(pts[1].x - pts[0].x, pts[1].y - pts[0].y) < size * 0.08) {
          ctx.arc(pts[0].x, pts[0].y, lw * 0.6, 0, Math.PI * 2); ctx.fillStyle = ctx.strokeStyle; ctx.fill();
          continue;
        }
        const off = p === 0 ? pts : pts.map((q, k) => v2(q.x + jit(seed + 77 + p, k, boil) * lw * 0.4, q.y + jit(seed + 78 + p, k, boil) * lw * 0.4));
        smoothOpen(ctx, off, pts.length > 5 ? 1 : 0);
        ctx.stroke();
      }
    }
    cx += (g.w + 0.26 + (st.tracking || 0)) * size;
  }
  ctx.restore();
  return total;
}

/** Multi-line helper: lines are drawn with the given line height. */
export function handLines(ctx: C2D, lines: string[], x: number, y: number, size: number, lh: number, st: HandStyle = {}) {
  lines.forEach((l, i) => handText(ctx, l, x, y + i * lh, size, { ...st, seed: (st.seed ?? 1) + i * 17 }));
}
