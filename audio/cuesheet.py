#!/usr/bin/env python3
"""Generates audio/CUE_SHEET.md from the score's statement log and the foley spotting list."""
import os, sys, json
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from common import OUT, HERE, SHOT, FPS, BLAZE, CLICK, LENGTH

S = json.load(open(os.path.join(OUT, 'statements.json')))
E = json.load(open(os.path.join(OUT, 'foley_events.json')))

def shot_of(t):
    for k, (a, b) in SHOT.items():
        if a <= t < b:
            return '%s+%.2f' % (k, t - a)
    return 'end'

def tc(t):
    f = int(round(t * FPS)); return '%d:%02d:%02d (f%d)' % (f // (60 * FPS), (f // FPS) % 60, f % FPS, f)

L = []
L.append('# CUE SHEET: Seen From Space\n')
L.append('*Generated by `audio/cuesheet.py` from the score and foley spotting lists. Times are in seconds from the first frame, then shot+offset, then m:ss:ff with the frame number at 24 fps.*\n')
L.append('## The motif\n')
L.append('The motif is eight notes in D major, in 3/4: **A4 F#4 G4 A4 | D5 (dotted) C#5 E5 | (D5)**, harmonised **D | G A | (D)**.')
L.append('The eighth note, the tonic **D5**, is withheld every time the motif plays before the blaze. A rest stands where the resolution should be, like a dead bulb in a string. Each scene ends unresolved, hanging on E5 over A.\n')
L.append('**The missing note lands for the first time at %.3f s (shot I4 + 0.00, frame %d)**, sample-accurately, on celesta, piano and glockenspiel together. The full arrangement blooms around it: strings, choir pad, low strings, harp glissando and timpani. Measured onsets in the rendered stems: celesta 136.503 s, piano 136.507 s, glock 136.507 s.\n' % (BLAZE, round(BLAZE * FPS)))
L.append('After the blaze the motif is heard **complete** twice: once with full orchestra and choir in J1, and once softly on celesta in the coda K1.\n')
L.append('## Sync points the picture must hit\n')
L.append('| What | Time (s) | Shot | Timecode |')
L.append('|---|---|---|---|')
L.append('| Music STOPS DEAD at the end of the Christmas Eve build | %.3f | %s | %s |' % (S['stop_dead'], shot_of(S['stop_dead'] - 1e-6), tc(S['stop_dead'])))
for (sh, t, p) in S['card_notes']:
    L.append('| Cue-card celesta note %s | %.3f | %s | %s |' % (p, t, shot_of(t), tc(t)))
L.append('| **THE DEAD CLICK**: switch flipped, all music cut to digital silence | %.3f | %s | %s |' % (CLICK, shot_of(CLICK), tc(CLICK)))
L.append('| Music silent (wind only) | %.2f to 128.60 | H4 to I1+0.6 | |' % CLICK)
for i, t in enumerate(S['bulb_times']):
    L.append('| Grandad\'s finger touches bulb %d (piano note) | %.3f | %s | %s |' % (i + 1, t, shot_of(t), tc(t)))
L.append('| Bulb twist squeak and seat click (ends at the blaze) | %.3f | %s | %s |' % (BLAZE - 0.32, shot_of(BLAZE - 0.32), tc(BLAZE - 0.32)))
L.append('| **BLAZE: the missing D5 lands** | **%.3f** | **I4+0.00** | **%s** |' % (BLAZE, tc(BLAZE)))
for i, t in enumerate(S['house_times']):
    L.append('| House %d down the street comes on (glock note) | %.3f | %s | %s |' % (i + 1, t, shot_of(t), tc(t)))
L.append('')
L.append('## Motif statements\n')
L.append('| Statement | Starts (s) | Where the D5 belongs / gap (s) | Resolved? |')
L.append('|---|---|---|---|')
for (label, t0, gap, res) in S['statements']:
    L.append('| %s | %.2f (%s) | %.2f (%s) | %s |' % (label, t0, shot_of(t0), gap, shot_of(gap), '**YES**' if res else 'no, a rest'))
L.append('')
L.append('## Instrumentation by sequence\n')
rows = [
 ('A 0:00 The only dark house', 'Celesta solo with a soft rolled left hand. The motif plays twice, and the gap of the second falls on the photo (A5). A barely-there string bed sits underneath. Wind outside, then the clock enters at A3.'),
 ('B 0:17 Nell decides', 'Clock only (B1–B2). Solo piano plays the motif at the decision (B3). A pizzicato pick-up comes in at B4.'),
 ('C 0:27 The shed', 'A tiptoe pizzicato ostinato. Three tender celesta notes on Grandma\'s handwriting (C2), then a staccato celesta motif and a tail that stops on the gap.'),
 ('D 0:39 The Operation', 'A 120 bpm caper (original) on pizzicato bass, spiccato string stabs, celesta and glock. Bulb plinks land on the beat (48.0–49.5). The strings take the motif broad at D6, where three glock hits mark the tally. A full rest at D7 for the thump, then a comic two-note pizz button. A lighter celesta statement at D8. The climax at D9 ends on a stab of E over A at 63.5, then silence.'),
 ('E 1:04 The Turn', 'Near silence: a faint high A under slow typing (E1). Gentle piano for the reply (E2), where the gap reads as a question. The strings swell Bm–G–D/F#–A on the reveal (E3).'),
 ('F 1:16 Knocking on doors', 'A pizz march. Each neighbour gets a fragment of the motif: celesta (old lady), glock (shop), pizz (teens), tiny high celesta and a trill (baby). F6 holds one low tremolo, then silence after the door slam, then the ladder clank. The full ensemble plays the motif on his nod, still without its last note.'),
 ('G 1:34 Christmas Eve', 'Distant church bells and a thread of tremolo (G1). Then a glock ostinato and building strings, bass and pizz over D–Bm–G–A, with strings and choir taking the motif at G5. The music **STOPS DEAD at 109.0**.'),
 ('H 1:49 The Dead Switch', 'Footsteps and wind, then a hush. The celesta spells the motif one note per cue card, and the D5 would fall exactly on the switch. **CLICK at 122.75**, and all music is cut. H5 is wind only.'),
 ('I 2:08 Grandad finishes it', 'Soft piano as he kneels. One piano note per bulb (I2). The gap is held with a faint rising thread (I3). **136.5: the D5 lands.** Strings, choir, low strings, harp glissando and timpani bloom. One glock note per house as the street comes on (I5). Warm strings and the porch bell (I6).'),
 ('J 2:27 Seen from space', 'The motif complete for the first time on strings in octaves, choir and celesta, with harp arpeggios and an airy whoosh. Then G–A–D, rising to a high D.'),
 ('K 2:37 Coda', 'Celesta plays the motif complete, softly, once, with the clock ticking.'),
 ('L 2:43 End card', 'A final D add9 chord on slow strings, choir and high celesta rings out, faded to silence by 168.0.'),
]
L.append('| Sequence | Music |'); L.append('|---|---|')
for a, b in rows:
    L.append('| %s | %s |' % (a, b))
L.append('')
L.append('## Foley (all synthesised)\n')
L.append('| Time (s) | Shot | Event | Bus |'); L.append('|---|---|---|---|')
for (t, name, bus) in E:
    L.append('| %.2f | %s | %s | %s |' % (t, shot_of(t), name, bus))
L.append('| 0.00 to 168.00 | all | Wind bed: full on exteriors, muffled and low-passed on interiors, prominent in H5, silent on the end card | wind |')
L.append('')
L.append('## Mix and master\n')
L.append('- 48 kHz stereo, 24-bit, exactly %.1f s. **-14 LUFS integrated, true peak -1.3 dBTP.**' % LENGTH)
L.append('- Music: a synthetic convolution hall (RT60 2.2 s) and two gentle bus compressors. The hall return is cut 30 ms after the click, so H5 has no music tail at all.')
L.append('- Interior foley goes through a small room. Exterior foley is nearly dry, because snow absorbs sound.')
L.append('- Rebuild with: `python3 audio/score.py && python3 audio/foley.py && python3 audio/mix.py && python3 audio/cuesheet.py`')
open(os.path.join(HERE, 'CUE_SHEET.md'), 'w').write('\n'.join(L) + '\n')
print('wrote CUE_SHEET.md')
